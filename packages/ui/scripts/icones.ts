const racine = dirname(
  createRequire(import.meta.url).resolve('@material-symbols/svg-400/package.json'),
);

const chemins = NOMS.map((nom) => {
  const svg = readFileSync(join(racine, 'rounded', `${nom}.svg`), 'utf8');
  const d = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join(' ');
  if (!d) throw new Error(`No path in ${nom}.svg`);
  return `  ${nom.replace('-fill', '_fill')}: '${d}',`;
});

const sortie = `// Generated by scripts/icones.ts from @material-symbols/svg-400 (rounded), do not edit.
export const ICONES = {
${chemins.join('\n')}
} as const;

export type NomIcone = keyof typeof ICONES;
`;

writeFileSync(join(import.meta.dirname, '..', 'src', 'icones.generated.ts'), sortie);
console.log(`${NOMS.length} icons written`);
